_KEY_RE = re.compile("(?:^| )(" + "|".join(map(re.escape, sorted(PARAM_KEYS, key=len, reverse=True))) + ")(?= |$)")

# Заглушка из прайс-листа Авито («Услуга Своя услуга»), смысловой нагрузки не несёт.
_PRICE_LIST_STUB = "Своя услуга"


def parse_params(text: str | None) -> dict[str, list[str]]:
    """Возвращает {ключ: [значения]}. Ключ может повторяться (позиции прайса, дни недели)."""
    out: dict[str, list[str]] = {}
    if not text:
        return out
    marks = list(_KEY_RE.finditer(text))
    for m, nxt in zip(marks, marks[1:] + [None]):
        value = text[m.end() : nxt.start() if nxt else len(text)].strip()
        out.setdefault(m.group(1), []).append(value)
    return out


def _first(d: dict[str, list[str]], key: str) -> str:
    """Первое непустое значение ключа или пустая строка."""
    return next((v for v in d.get(key, []) if v), "")


def _joined(d: dict[str, list[str]], keys: list[str], skip: set[str] = frozenset()) -> str:
    """Все уникальные непустые значения набора ключей через « | » (порядок сохраняется)."""
    seen: dict[str, None] = {}
    for k in keys:
        for v in d.get(k, []):
            if v and v not in skip:
                seen.setdefault(v, None)
    return " | ".join(seen)


def _has(d: dict[str, list[str]], key: str, needle: str) -> bool:
    """Есть ли подстрока needle хотя бы в одном значении ключа (см. ограничение в docstring модуля)."""
    return any(needle in v for v in d.get(key, []))


def parse_experience_years(values: list[str]) -> float | None:
    """Опыт работы в годах из форматов «Меньше года», «1–3 года», «4–6 лет», «Больше 10 лет», «10»."""
    for v in values:
        v = v.lower()
        if "меньше года" in v:
            return 0.5
        nums = [int(x) for x in re.findall(r"\d+", v)[:2]]
        if not nums:
            continue
        if "больше" in v:
            return float(nums[0])
        if len(nums) == 2 and re.search(r"\d+\s*[–-]\s*\d+", v):
            return (nums[0] + nums[1]) / 2
        return float(nums[0])
    return None


def extract_item_fields(text: str | None) -> dict[str, object]:
    """Структурированные поля объявления из item_infm_params_text."""
    d = parse_params(text)
    return {
        # Классификация — для фильтров и признаков совпадения с фильтрами поиска.
        "vid": _first(d, "Вид услуги"),
        "tip": _first(d, "Тип услуги"),
        "tip_auto": _first(d, "Тип услуги автосервиса"),
        "subject": _joined(
            d,
            [
                "Предмет или специальность",
                "Специальность или сфера",
                "Специальность",
                "Чем вы занимаетесь",
                "Направление",
            ],
        ),
        # Текстовые поля для поиска.
        "price_list": _joined(d, ["Название услуги", "Услуга"], skip={_PRICE_LIST_STUB}),
        "brands": _joined(d, ["Марка авто", "Модель", "Производители", "Техника"]),
        "address": _first(d, "Место оказания услуг"),
        # Формат работы: слабые сигналы (разница 1.2–2 раза), только как признаки ранжирования.
        "work_remote": _has(d, "Как вы работаете", "Удалённ"),
        "work_online": _has(d, "Как вы работаете", "Онлайн"),
        "work_at_client": _has(d, "Как вы работаете", "У клиента")
        or _has(d, "Где вы оказываете услуги", "У заказчика"),
        "work_at_self": _has(d, "Как вы работаете", "У себя")
        or _has(d, "Где вы оказываете услуги", "У себя")
        or _has(d, "Где вы оказываете услуги", "В салоне"),
        "travel_city": _has(d, "Куда выезжаете", "По всему городу"),
        "travel_region": _has(d, "Куда выезжаете", "В области"),
        "travel_zones": _has(d, "Куда выезжаете", "В выбранные зоны"),
        "travel_none": _has(d, "Куда выезжаете", "Не выезжаю"),
        # Онлайн-запись: при одноимённом фильтре ключ у выбранных в 12 раз чаще среднего.
        "online_booking": "Онлайн-запись" in d,
        "has_contract": "Работа по договору" in d,
        "has_guarantee": "Гарантия" in d or "Гарантия на работу" in d,
        "works_with_legal": "Работаете с юрлицами и ИП" in d,
        "experience_years": parse_experience_years(d.get("Опыт работы", [])),
        "price_list_size": sum(1 for v in d.get("Название услуги", []) if v)
        + sum(1 for v in d.get("Услуга", []) if v and v != _PRICE_LIST_STUB),
    }


def extract_search_filters(text: str | None) -> dict[str, object]:
    """Структурированные фильтры поиска из search_infm_params_text."""
    d = parse_params(text)
    return {
        "f_vid": _first(d, "Вид услуги"),
        "f_tip": _first(d, "Тип услуги"),
        "f_tip_auto": _first(d, "Тип услуги автосервиса"),
        "f_subject": _first(d, "Предмет или специальность"),
        "f_who": _joined(d, ["Кто оказывает услуги"]),
        "f_online_booking": "Онлайн-запись" in d,
        "f_keys": " | ".join(sorted(d)),
    }
